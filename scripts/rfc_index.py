#!/usr/bin/env python3
"""Generate the RFC ledger index in rfcs/README.md from each file's frontmatter.

Standard library only (runs under a bare ``python3`` and in the weekly gate,
which has no virtualenv). Read-only on ``rfcs/*.md`` and ``docs/adr/*.md``;
the only file it writes is ``rfcs/README.md``, and only between the two
marker comments.

Why it exists (ROADMAP P1-02.3 / .4): the README table used to be a
hand-kept two-column list (``| # | Title |``) that said nothing about state,
so a reader had to open 54 files, or run the harness-side ``claims.py``, to
learn which proposals were open. ``rfcs/README.md`` states that the
frontmatter is the single source of truth; this script makes the README a
projection of it, and ``tests/test_rfc_frontmatter.py`` fails when the
committed README differs from this script's output.

Frontmatter format (one form for every RFC; checked by ``validate``):

    title:           one line, shown in the index (required from ``accepted`` on)
    state:           one word (draft | accepted | in_progress | blocked |
                     done | resolved | obsoleted | withdrawn | rejected)
    state_since:     YYYY-MM-DD, the day the RFC entered the current state
    review-when:     required from ``accepted`` on, unless the state is terminal
                     (a ``draft`` needs only state + state_since: the weekly chain
                     files drafts with just those, and the Saturday gate fills the rest)
    decide_by:       blocked only, YYYY-MM-DD: if the unblock condition is not
                     met by then, withdraw or shrink the question
    next_check:      blocked only, YYYY-MM-DD: nobody re-checks or appends a
                     triage note before this date
    admitted-by:     accepted / done only: ``<name> YYYY-MM-DD`` or the literal
                     ``unrecorded`` (never invented from git authorship)
    decided-by:      optional, same shape as admitted-by
    alignment:       required while open and past draft (accepted / in_progress /
                     blocked): repair | instrument | capability-growth |
                     value-steering-risk (the ADR-0080 review axis)
    decision_needed: optional one-line question awaiting the owner

Usage:
    python3 scripts/rfc_index.py            # rewrite the block in rfcs/README.md
    python3 scripts/rfc_index.py --check    # exit 1 if README.md is stale
    python3 scripts/rfc_index.py --validate # exit 1 if any RFC breaks the format
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RFC_DIR = REPO / "rfcs"
ADR_DIR = REPO / "docs" / "adr"

BEGIN = "<!-- rfc-index:begin (generated by scripts/rfc_index.py; edit the RFC frontmatter, not this block) -->"
END = "<!-- rfc-index:end -->"

STATES = (
    "draft",
    "accepted",
    "in_progress",
    "blocked",
    "done",
    "resolved",
    "obsoleted",
    "withdrawn",
    "rejected",
)
TERMINAL = frozenset({"done", "resolved", "obsoleted", "withdrawn", "rejected"})
OPEN = frozenset(STATES) - TERMINAL
ALIGNMENTS = ("repair", "instrument", "capability-growth", "value-steering-risk")

# First line under every ``## 決定の記録``: the section is a dated log, not the state.
RECORD_LEAD = "記録時点の経過（現在の state は frontmatter の `state:`）。"
_DATED_WORD = re.compile(r"[`*_~(（]*[A-Za-z_]+[`*_~)）]*\s*[—（(]?\s*\d{4}-\d{2}-\d{2}")
_DATE = re.compile(r"\d{4}-\d{2}-\d{2}")
_ADMIT = re.compile(r"unrecorded|\S+ \d{4}-\d{2}-\d{2}")
AWAITING_MARK = "Deferred — 未決"


@dataclass(frozen=True)
class Rfc:
    number: str
    path: Path
    fields: dict[str, str]
    body: str

    @property
    def state(self) -> str:
        return self.fields.get("state", "")


def parse(path: Path) -> Rfc:
    text = path.read_text(encoding="utf-8")
    fields: dict[str, str] = {}
    body = text
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end != -1:
            for line in text[4:end].split("\n"):
                if ": " in line:
                    key, value = line.split(": ", 1)
                    fields[key.strip()] = value.strip()
            body = text[end + 5 :]
    return Rfc(path.name[:4], path, fields, body)


def load(rfc_dir: Path = RFC_DIR) -> list[Rfc]:
    return [parse(p) for p in sorted(rfc_dir.glob("[0-9][0-9][0-9][0-9]-*.md"))]


def body_status_first_word(rfc: Rfc) -> str | None:
    """First word of the body's ``## Status`` section, or None if it has none."""
    match = re.search(r"^## Status\s*\n+(.*)", rfc.body, re.M)
    if match is None:
        return None
    first = re.match(r"[`*_~(（]*([A-Za-z_]+)", match.group(1).strip())
    return first.group(1) if first else ""


def _date_problems(f: dict[str, str], state: str) -> list[str]:
    problems: list[str] = []
    if not _DATE.fullmatch(f.get("state_since", "")):
        problems.append("state_since missing or not YYYY-MM-DD")
    if state != "blocked":
        return problems
    for key in ("decide_by", "next_check"):
        if not _DATE.fullmatch(f.get(key, "")):
            problems.append(f"{key} required (YYYY-MM-DD) while blocked")
    if len(problems) == 0 and f["next_check"] > f["decide_by"]:
        problems.append("next_check is later than decide_by")
    return problems


def _admission_problems(f: dict[str, str], state: str) -> list[str]:
    problems: list[str] = []
    if state in ("accepted", "done") and not _ADMIT.fullmatch(f.get("admitted-by", "")):
        problems.append("admitted-by required: '<name> YYYY-MM-DD' or 'unrecorded'")
    if "decided-by" in f and not _ADMIT.fullmatch(f["decided-by"]):
        problems.append("decided-by must be '<name> YYYY-MM-DD' or 'unrecorded'")
    return problems


def record_problems(rfc: Rfc) -> list[str]:
    """The ``## 決定の記録`` section must carry the lead line and no undated state claim."""
    match = re.search(r"^## 決定の記録\s*\n+(.*)\n+(.*)", rfc.body, re.M)
    if match is None:
        return []
    if match.group(1).strip() != RECORD_LEAD:
        return [
            "'## 決定の記録' must open with the lead line (see scripts/rfc_index.py RECORD_LEAD)"
        ]
    first = match.group(2).strip()
    word = re.match(r"[`*_~(（]*([A-Za-z_]+)", first)
    if (
        word
        and word.group(1) in STATES
        and word.group(1) != rfc.state
        and not _DATED_WORD.match(first)
    ):
        return [
            f"'## 決定の記録' leads with undated state word {word.group(1)!r} (frontmatter: {rfc.state!r})"
        ]
    return []


def validate(rfc: Rfc) -> list[str]:
    """Format violations of one RFC; an empty list means it conforms."""
    f = rfc.fields
    state = f.get("state", "")
    problems: list[str] = []
    gated = state in STATES and state != "draft"  # a draft needs only state + state_since
    if gated and not f.get("title"):
        problems.append("title missing")
    if state not in STATES:
        problems.append(f"state {state!r} is not one bare word of {STATES}")
    if gated and state in OPEN and not f.get("review-when"):
        problems.append("review-when required for a non-terminal state")
    if gated and state in OPEN and f.get("alignment") not in ALIGNMENTS:
        problems.append(f"alignment required while open, one of {ALIGNMENTS}")
    elif "alignment" in f and f["alignment"] not in ALIGNMENTS:
        problems.append(f"alignment {f['alignment']!r} not in {ALIGNMENTS}")
    problems += _date_problems(f, state) + _admission_problems(f, state)
    status = body_status_first_word(rfc)
    if status is not None and status != state:
        problems.append(f"body '## Status' says {status!r}, frontmatter says {state!r}")
    return problems + record_problems(rfc)


def _first_clause(text: str, limit: int = 70) -> str:
    clause = re.split(r"[。]", text, maxsplit=1)[0].strip()
    if len(clause) > limit:
        clause = clause[: limit - 1].rstrip() + "…"
    return clause.replace("|", "\\|")


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def awaiting_from_adrs(adr_dir: Path = ADR_DIR) -> list[tuple[str, int, str]]:
    found: list[tuple[str, int, str]] = []
    for path in sorted(adr_dir.glob("[0-9][0-9][0-9][0-9]-*.md")):
        if path.name.endswith(".ja.md"):
            continue
        for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if AWAITING_MARK in line:
                found.append((path.name, lineno, line.strip()))
    return found


def render(rfcs: list[Rfc], adr_dir: Path = ADR_DIR) -> str:
    counts = {s: sum(1 for r in rfcs if r.state == s) for s in STATES}
    shown = " / ".join(f"{s} {counts[s]}" for s in STATES if counts[s])
    lines = [BEGIN, "", f"{len(rfcs)} 件: {shown}。", ""]
    lines += [
        "| # | Title | state | since | decide_by | review-when | 再開条件 |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rfcs:
        f = r.fields
        review = f.get("review-when", "")
        resume = _first_clause(review) if r.state in OPEN and review else "—"
        lines.append(
            f"| [{r.number}]({r.path.name}) | {_cell(f.get('title', '(title なし)'))} | {r.state} "
            f"| {f.get('state_since', '—')} | {f.get('decide_by', '—')} "
            f"| {'有' if review else '—'} | {resume} |"
        )
    lines += ["", "### awaiting-owner（オーナーの決定待ち）", ""]
    asked = [r for r in rfcs if r.state in OPEN and r.fields.get("decision_needed")]
    if asked:
        for r in asked:
            when = f"（decide_by {r.fields['decide_by']}）" if "decide_by" in r.fields else ""
            lines.append(f"- [RFC-{r.number}]({r.path.name}) — {r.fields['decision_needed']}{when}")
    else:
        lines.append("- RFC: なし")
    adr_hits = awaiting_from_adrs(adr_dir)
    if adr_hits:
        for name, lineno, _ in adr_hits:
            lines.append(
                f"- [ADR {name[:4]}](../docs/adr/{name}) の {lineno} 行目（`{AWAITING_MARK}`）"
            )
    else:
        lines.append(f"- ADR: 本文に `{AWAITING_MARK}` の行なし")
    lines += ["", "### alignment（ADR-0080 の審査軸、open の RFC）", ""]
    for a in ALIGNMENTS:
        names = [
            f"RFC-{r.number}" for r in rfcs if r.state in OPEN and r.fields.get("alignment") == a
        ]
        lines.append(f"- {a}: {len(names)}" + (f"（{', '.join(names)}）" if names else ""))
    lines += ["", END]
    return "\n".join(lines)


def splice(readme: str, block: str) -> str:
    start = readme.find(BEGIN)
    end = readme.find(END)
    if start == -1 or end == -1 or end < start:
        raise SystemExit("rfcs/README.md has no rfc-index markers")
    return readme[:start] + block + readme[end + len(END) :]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if README.md is stale")
    ap.add_argument("--validate", action="store_true", help="exit 1 on frontmatter violations")
    args = ap.parse_args(argv)

    rfcs = load()
    if args.validate:
        bad = {r.path.name: validate(r) for r in rfcs}
        bad = {k: v for k, v in bad.items() if v}
        for name, problems in bad.items():
            print(f"{name}: " + "; ".join(problems), file=sys.stderr)
        return 1 if bad else 0

    readme_path = RFC_DIR / "README.md"
    current = readme_path.read_text(encoding="utf-8")
    updated = splice(current, render(rfcs))
    if args.check:
        if updated != current:
            print("rfcs/README.md is stale; run python3 scripts/rfc_index.py", file=sys.stderr)
            return 1
        return 0
    if updated != current:
        readme_path.write_text(updated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
