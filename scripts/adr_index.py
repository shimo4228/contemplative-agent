#!/usr/bin/env python3
"""Generate the ADR index tables of docs/adr/README.md and README.ja.md from the ADR bodies.

stdlib only (run it with bare ``python3``). The index used to be hand-written:
113 rows x 2 faces that drifted from the bodies (a bare ``accepted`` for an
amended ADR, a Date nobody could regenerate, an index that showed no movement
in a month where 22 bodies changed). The bodies are the source of truth; the
table between the two ``adr-index`` markers is derived from them and a test
(``tests/test_adr_index_generated.py``) fails when the committed table differs
from the generated one.

    python3 scripts/adr_index.py                    # rewrite both tables
    python3 scripts/adr_index.py --check            # exit 1 if a table is stale
    python3 scripts/adr_index.py --revised-since 30 # how many ADRs changed in 30 days

What each column is derived from (English body for Status / Date / dates; the
ja twin only for its own title):

- Title        the H1 minus the ``ADR-NNNN:`` prefix (and a trailing
               ``(withdrawn …)`` note), plus the ``[AKC: …]`` tag, if any
- Status       the *spine* of the body's Status block: the leading term, an
               ``(amended D1, D2)`` tail, and the relation phrases with their
               ADR numbers. Free-text tails and parentheticals are dropped, so
               ADR numbers are bare (``0097``), sorted, and the index stays a
               short face. ``(note)`` and a withdrawal date are kept.
- Date         the body's ``## Date``
- Last revised the latest of Date, the dated Amendment blocks and the dated
               ``Note`` / ``Postscript`` lines in the body
- AAP          reserved and empty: it is filled from the agent-attribution-practice
               correspondence table once that table exists; no ADR claims a
               correspondence here until then

The ``[AKC: …]`` tag is generated from ``graph.jsonld``: the six ``Phase``
nodes are the canonical AKC phase mapping, and an ADR named in a phase's
``realizedBy`` carries that phase's English name (several phases in phase
order, joined by ``/``). An ADR no phase names has no tag. To change a tag,
edit the phase node's ``realizedBy`` and re-run this script.

Consumption plan (ADR-0101, proposal for owner review): ``--revised-since`` is
a read-only count. (a) The Saturday-gate reader who asks whether the ADR set is
moving looks at it; nothing else calls it. (b) It is shown next to the number of
newly written ADRs, so a month with no new ADR but 20 revised bodies does not
read as "stopped". (c) Delete the flag if four consecutive gates do not read it.
The table generation is not an instrument: it changes no reading.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import date, timedelta
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ADR_DIR = REPO / "docs" / "adr"
GRAPH = REPO / "graph.jsonld"

BEGIN = "<!-- adr-index:begin (generated by scripts/adr_index.py — do not edit by hand) -->"
END = "<!-- adr-index:end -->"

PHASE_PREFIX = "https://shimo4228.github.io/shimo4228/vocab#ca/phase/"
_ADR_URL_RE = re.compile(r"/docs/adr/(\d{4})-[^/]*\.md$")


def _as_list(value: object) -> list[str]:
    """A JSON-LD edge as a list: absent, one IRI string, or a list of them."""
    if isinstance(value, str):
        return [value]
    if isinstance(value, list):
        return [str(v) for v in value]
    return []


def phase_nodes(graph: dict) -> list[dict]:
    """The six AKC Phase nodes, in phase order."""
    nodes = [n for n in graph["@graph"] if str(n.get("@id", "")).startswith(PHASE_PREFIX)]
    return sorted(nodes, key=lambda n: int(n["order"]))


def phase_name(node: dict) -> str:
    """The phase's English name (``Research`` … ``Maintain``)."""
    for alt in node.get("alternateName", []):
        if isinstance(alt, dict) and alt.get("@language") == "en":
            return str(alt["@value"])
    raise ValueError(f"{node['@id']}: no English alternateName")


def akc_tags(graph: dict) -> dict[str, str]:
    """ADR number -> ``Extract/Curate``: the phases whose ``realizedBy`` names it."""
    tags: dict[str, list[str]] = {}
    for node in phase_nodes(graph):
        for url in _as_list(node.get("realizedBy")):
            if m := _ADR_URL_RE.search(url):
                tags.setdefault(m.group(1), []).append(phase_name(node))
    return {adr: "/".join(names) for adr, names in tags.items()}


def load_graph() -> dict:
    return json.loads(GRAPH.read_text(encoding="utf-8"))


_HEADS = (
    "partially-superseded-by",
    "superseded-by",
    "withdrawn-by",
    "withdrawn",
    "accepted",
    "proposed",
    "rejected",
)
_BACKWARD = {"partially-superseded-by", "superseded-by", "withdrawn-by"}
# Longest first: a phrase that is a prefix of another must not shadow it.
_RELATIONS = (
    "partially-superseded-by",
    "partially-supersedes",
    "operationalizes",
    "superseded-by",
    "withdrawn-by",
    "supersedes",
    "extends",
)
_PHRASE_RE = re.compile("|".join(r.replace("-", "[- ]") for r in _RELATIONS))
_REF = r"(?:ADR-)?(0\d{3})\b"
_REF_RUN_RE = re.compile(r"[\s,/;]*(?:and\s+)?" + _REF)

_AMENDMENT_RE = re.compile(
    r"^(?:## Amendment\b[^()\n]*|\*\*[A-Za-z0-9 ]*amendment )\((\d{4}-\d\d-\d\d)", re.M
)
_NOTE_DATE_RE = re.compile(
    r"\b(?:Note|Postscript)\b[^\n]{0,60}?(\d{4}-\d\d-\d\d)|注記[（(](\d{4}-\d\d-\d\d)"
)
_DATE_RE = re.compile(r"\d{4}-\d\d-\d\d")


def _adr_files(suffix: str) -> dict[str, Path]:
    out: dict[str, Path] = {}
    for path in sorted(ADR_DIR.glob("0*.md")):
        is_ja = path.name.endswith(".ja.md")
        if is_ja != (suffix == ".ja.md"):
            continue
        out[path.name[:4]] = path
    return out


def _status_block(text: str) -> str | None:
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if line.strip() in ("## Status", "## ステータス"):
            block: list[str] = []
            for nxt in lines[i + 1 :]:
                if nxt.startswith("## "):
                    break
                if nxt.strip():
                    block.append(nxt.strip())
                elif block:
                    break
            return " ".join(block) or None
    return None


def _section_date(text: str) -> str | None:
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if line.strip() in ("## Date", "## 日付"):
            for nxt in lines[i + 1 : i + 6]:
                if m := _DATE_RE.search(nxt):
                    return m.group(0)
    return None


def _title(text: str) -> str:
    first = text.splitlines()[0]
    title = re.sub(r"^#\s*ADR-\d{4}:\s*", "", first).strip()
    # The withdrawal date is a Status fact, not part of the name.
    return re.sub(r"\s*[（(](?:withdrawn|撤回)[^)）]*[)）]$", "", title)


def _strip_parentheticals(text: str) -> str:
    prev = None
    while prev != text:
        prev = text
        text = re.sub(r"\([^()]*\)|（[^（）]*）", "", text)
    return text


def _refs_after(text: str, pos: int) -> list[str]:
    refs: list[str] = []
    while m := _REF_RUN_RE.match(text, pos):
        refs.append(m.group(1))
        pos = m.end()
    return refs


def status_cell(adr: str, text: str) -> str:  # noqa: C901 — one spine, many Status shapes
    """The short Status face derived from one ADR's English body."""
    status = _status_block(text) or ""
    plain = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", status).replace("**", "")
    plain = re.sub(r"\s+", " ", plain).strip()
    low = plain.lower()
    lead = next(
        (h for h in _HEADS if low.startswith(h) or low.startswith(h.replace("-", " "))), None
    )
    if lead is None:
        raise ValueError(f"ADR-{adr}: Status {status!r} starts with no documented term")

    dates = list(dict.fromkeys(_AMENDMENT_RE.findall(text)))
    if not dates and (m := re.search(r"amended\s+((?:\d{4}-\d\d-\d\d(?:,\s*)?)+)", plain)):
        dates = _DATE_RE.findall(m.group(1))

    bare = re.sub(r"\s+", " ", _strip_parentheticals(plain))
    lead_match = re.match(lead.replace("-", "[- ]"), bare, re.I)
    assert lead_match is not None
    rest_pos = lead_match.end()
    # Relation clauses after the leading term, each phrase with its numbers.
    clauses: list[tuple[str, set[str]]] = []
    for match in _PHRASE_RE.finditer(bare, rest_pos):
        phrase = match.group(0).replace(" ", "-")
        refs = {r for r in _refs_after(bare, match.end()) if r != adr}
        if refs:
            clauses.append((phrase, refs))

    base = lead
    if lead in _BACKWARD:
        refs = {r for r in _refs_after(bare, rest_pos) if r != adr}
        # "partially-superseded-by A … ; partially-superseded-by B" is one lead.
        for phrase, more in clauses:
            if phrase == lead:
                refs |= more
        clauses = [(p, r) for p, r in clauses if p != lead]
        if refs:
            base = f"{lead} {', '.join(sorted(refs))}"
    elif lead == "withdrawn" and (m := re.match(r"withdrawn\s*\((\d{4}-\d\d-\d\d)\)", plain, re.I)):
        base = f"withdrawn ({m.group(1)})"
    elif lead == "accepted" and low.startswith("accepted (note)"):
        base = "accepted (note)"
    if dates:
        base += f" (amended {', '.join(dates)})"
    merged: dict[str, set[str]] = {}
    for phrase, refs in clauses:  # repeated phrases (ADR-0113 x3) read as one clause
        merged.setdefault(phrase, set()).update(refs)
    if merged:
        base += " — " + "; ".join(f"{p} {', '.join(sorted(r))}" for p, r in merged.items())
    return base


def last_revised(text: str) -> str:
    """Latest dated event in the body: Date, Amendment blocks, Notes, Postscripts."""
    found = [d for d in [_section_date(text)] if d]
    found += _AMENDMENT_RE.findall(text)
    for m in _NOTE_DATE_RE.finditer(text):
        found.append(m.group(1) or m.group(2))
    return max(found)


def _rows(ja: bool) -> list[dict[str, str]]:
    en = _adr_files(".md")
    own = _adr_files(".ja.md") if ja else en
    tags = akc_tags(load_graph())
    rows = []
    for adr, en_path in en.items():
        en_text = en_path.read_text(encoding="utf-8")
        own_path = own[adr]
        title = _title(own_path.read_text(encoding="utf-8"))
        if adr in tags:
            title += f" `[AKC: {tags[adr]}]`"
        rows.append(
            {
                "adr": adr,
                "file": own_path.name,
                "title": title,
                "status": status_cell(adr, en_text),
                "date": _section_date(en_text) or "",
                "revised": last_revised(en_text),
            }
        )
    return rows


def render_table(ja: bool) -> str:
    head = (
        "| ADR | タイトル | Status | Date | Last revised | AAP |"
        if ja
        else "| ADR | Title | Status | Date | Last revised | AAP |"
    )
    lines = [head, "|-----|-------|--------|------|--------------|-----|"]
    for r in _rows(ja):
        lines.append(
            f"| [{r['adr']}]({r['file']}) | {r['title']} | {r['status']} | "
            f"{r['date']} | {r['revised']} |  |"
        )
    return "\n".join(lines)


def render_block(ja: bool) -> str:
    return f"{BEGIN}\n{render_table(ja)}\n{END}"


def splice(readme_text: str, block: str) -> str:
    """Replace the marked block; on first run, replace the hand-written table."""
    if BEGIN in readme_text:
        pre, rest = readme_text.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        return pre + block + post
    lines = readme_text.split("\n")
    start = next(i for i, ln in enumerate(lines) if ln.startswith("| ADR |"))
    end = start
    while end < len(lines) and lines[end].startswith("|"):
        end += 1
    return "\n".join(lines[:start] + block.split("\n") + lines[end:])


READMES = ((ADR_DIR / "README.md", False), (ADR_DIR / "README.ja.md", True))


def generated(path: Path, ja: bool) -> str:
    return splice(path.read_text(encoding="utf-8"), render_block(ja))


def revised_since(days: int, today: date) -> list[str]:
    cutoff = (today - timedelta(days=days)).isoformat()
    return [r["adr"] for r in _rows(False) if r["revised"] >= cutoff]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a committed table is stale")
    parser.add_argument(
        "--revised-since", type=int, metavar="DAYS", help="print the ADRs revised in the last DAYS"
    )
    parser.add_argument("--today", help="override today's date (YYYY-MM-DD), for tests")
    args = parser.parse_args(argv)

    if args.revised_since is not None:
        today = date.fromisoformat(args.today) if args.today else date.today()
        hits = revised_since(args.revised_since, today)
        print(f"{len(hits)} ADR(s) revised in the last {args.revised_since} days: {' '.join(hits)}")
        return 0

    stale = []
    for path, ja in READMES:
        new = generated(path, ja)
        if new != path.read_text(encoding="utf-8"):
            stale.append(path.name)
            if not args.check:
                path.write_text(new, encoding="utf-8")
    if args.check and stale:
        print(f"stale: {', '.join(stale)} — run python3 scripts/adr_index.py", file=sys.stderr)
        return 1
    if stale:
        print(f"rewrote: {', '.join(stale)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
