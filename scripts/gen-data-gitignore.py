#!/usr/bin/env python3
"""Print the public data repo's .gitignore from the shared exclude lists (P0-03.2).

stdlib only (run with bare python3). The data repo's .gitignore is hand-kept
there (sync-research-data.sh excludes it from the rsync), so this prints to
stdout and the owner redirects it in the DATA_REPO checkout with the sync job
unloaded:

    python3 scripts/gen-data-gitignore.py > "$DATA_REPO/.gitignore"

It is the second wall behind the sync's rsync excludes: `git add -A` honours it
even if a name slips past rsync. Patterns come from config/sync-excludes.txt
and config/sync-excludes-public.txt, so the three can not drift apart. The
receiver-owned governance files are deliberately not ignored.
"""

from __future__ import annotations

import sys
from pathlib import Path

CONFIG = Path(__file__).resolve().parent.parent / "config"
LISTS = ("sync-excludes.txt", "sync-excludes-public.txt")

# Local-only areas the data repo has always ignored (RFC-0053): kept here so a
# regenerated file does not lose them.
EXTRA = (".private", ".DS_Store")


def patterns() -> list[str]:
    seen: list[str] = []
    for name in LISTS:
        for line in (CONFIG / name).read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and line not in seen:
                seen.append(line)
    for line in EXTRA:
        if line not in seen:
            seen.append(line)
    return seen


def render() -> str:
    head = (
        "# Generated by scripts/gen-data-gitignore.py in the contemplative-agent repo\n"
        "# from config/sync-excludes*.txt. Do not edit by hand; regenerate.\n"
    )
    return head + "\n".join(patterns()) + "\n"


if __name__ == "__main__":
    sys.stdout.write(render())
