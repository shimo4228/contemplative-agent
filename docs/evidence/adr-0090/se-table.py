#!/usr/bin/env python3
"""Regenerate se-table.md: cell-wise SE of the four committed IPD runs (P3-03.10).

Public JSON only, no new run. Usage (from the repo root):
    python3 docs/evidence/adr-0090/se-table.py > docs/evidence/adr-0090/se-table.md
The estimator is the one in scripts/ipd_two_arm_report.py.
"""

import importlib.util
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location(
    "ipd_two_arm_report", os.path.join(HERE, "..", "..", "..", "scripts", "ipd_two_arm_report.py")
)
r = importlib.util.module_from_spec(spec)
spec.loader.exec_module(r)

RUNS = ["null-run-1", "null-run-2", "arm-A-current", "arm-B-staged"]
arms = {k: r.load_arm(os.path.join(HERE, k + ".json")) for k in RUNS}

print("# IPD cell-wise SE table (4 committed runs, n=10, gemma4:e4b)\n")
print("Generated by `se-table.py`. SE(cell) = std_dev / sqrt(n) (ddof=1) from each run's own")
print("statistics; effect = custom − baseline; SE(effect) = sqrt(SE_custom² + SE_baseline²).\n")
print("## Per-run effect and SE\n")
print("| run | α | baseline | SE | custom | SE | effect | SE(effect) |")
print("|---|---|---|---|---|---|---|---|")
for k in RUNS:
    a = arms[k]
    for al in r.ALPHAS:
        b, c = a["cells"][("baseline", al)]["mean_rate"], a["cells"][("custom", al)]["mean_rate"]
        print(
            f"| {k} | {al} | {b:.3f} | {a['ses'][('baseline', al)]:.3f} | {c:.3f} | "
            f"{a['ses'][('custom', al)]:.3f} | {c - b:+.3f} | {r.effect_se(a['ses'], al):.3f} |"
        )
print("\n## Pairs\n")
print("| pair | α | Δeffect | SE(Δ) | z | 2 SE floor | ±0.13 in SE |")
print("|---|---|---|---|---|---|---|")
for name, x, y in (("null pair (run-2 − run-1)", "null-run-1", "null-run-2"),
                   ("amendment (B − A)", "arm-A-current", "arm-B-staged")):
    for al in r.ALPHAS:
        d = r.effect(arms[y]["cells"], al) - r.effect(arms[x]["cells"], al)
        se = math.hypot(r.effect_se(arms[x]["ses"], al), r.effect_se(arms[y]["ses"], al))
        print(f"| {name} | {al} | {d:+.3f} | {se:.3f} | {r.z_of(d, se):+.2f} | {2 * se:.3f} | {r.NOISE_FLOOR / se:.1f} |")
print(
    "\nReading: the single ±0.13 floor is worth 2.7 SE at α=0.0 (conservative) but only "
    "1.8 and 1.9 SE at α=0.5 and α=1.0, i.e. under the 2 SE line there. The amendment run "
    "(B − A) reads z = +0.19 / 0.00 / −0.77, so the 2026-08-09 conclusion does not change."
)
